export const STRINGS = { uz: UZ, ru: RU, en: EN };

let lang = 'uz';
try {
  const saved = localStorage.getItem('penaplast-lang');
  if (saved && STRINGS[saved]) lang = saved;
} catch (_) {
  /* storage unavailable */
}

export const currentLang = () => lang;
export const t = (key) => STRINGS[lang][key] ?? STRINGS.uz[key] ?? key;

export function setLang(next) {
  if (!STRINGS[next] || next === lang) return;
  lang = next;
  try {
    localStorage.setItem('penaplast-lang', next);
  } catch (_) {
    /* ignore */
  }
  document.documentElement.lang = next === 'uz' ? 'uz' : next;
  document.title = t('meta.title');
  applyStaticI18n();
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

/** Translate all static [data-i18n] / [data-i18n-ph] nodes. */
export function applyStaticI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPh));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  const rights = document.getElementById('rights');
  if (rights) rights.textContent = t('footer.rights').replace('{y}', new Date().getFullYear());
}
